-- A SECURITY DEFINER helper so RLS policies can ask "what is this user's
-- role?" without recursively reading profiles through RLS. The name is
-- app_role(), not current_role, because current_role is reserved by Postgres.
create or replace function public.app_role()
returns text
language sql
stable
security definer
set search_path = public, auth
as $function$
    select p.role
    from public.profiles p
    where p.id = auth.uid()
      and p.is_active = true;
$function$;

-- Returns the counsellor directory row linked to the signed-in Auth user.
-- Only active profiles are accepted; a deactivated counsellor cannot manage
-- new sessions even if an old token is still around.
create or replace function public.app_counsellor_id()
returns uuid
language sql
stable
security definer
set search_path = public, auth
as $function$
    select c.id
    from public.counsellors c
    join public.profiles p on p.id = c.user_id
    where c.user_id = auth.uid()
      and p.role = 'counsellor'
      and p.is_active = true;
$function$;

