-- Public booking catalogue. It deliberately runs with the view owner's rights
-- (the Supabase default for views) so the NOT EXISTS check can see bookings
-- made by other students. Only safe, public fields are exposed. Every app
-- query filters on this view; students never query the appointments table for
-- another student.
create or replace view public.available_slots_view as
select
    s.id as slot_id,
    s.counsellor_id,
    c.full_name as counsellor_name,
    c.specialisations,
    c.languages,
    c.bio,
    s.start_at,
    s.end_at
from public.availability_slots s
join public.counsellors c on c.id = s.counsellor_id
where c.is_active = true
  and s.start_at > now()
  and not exists (
      select 1
      from public.appointments a
      where a.slot_id = s.id
        and a.status in ('pending', 'confirmed')
  );

-- Student-safe session summaries. Students have NO SELECT policy on
-- session_records; this owner-rights view exposes only the public summary and
-- never private_notes or risk_level. auth.uid() keeps it to the caller's rows.
create or replace view public.student_session_summaries as
select
    r.id as record_id,
    r.appointment_id,
    s.start_at as session_start,
    a.concern_category,
    c.full_name as counsellor_name,
    r.public_summary,
    r.created_at as summary_created_at
from public.session_records r
join public.appointments a on a.id = r.appointment_id
join public.availability_slots s on s.id = a.slot_id
join public.counsellors c on c.id = r.counsellor_id
where r.student_id = auth.uid()
  and r.is_archived = false
  and a.status = 'completed';

