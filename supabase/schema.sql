-- A counsellor directory entry is created by an admin before the counsellor
-- creates their Auth account. When the matching email signs up, the
-- auth.users trigger sets user_id and gives the new profile the counsellor role.
create table if not exists public.counsellors (
    id uuid primary key default gen_random_uuid(),
    user_id uuid unique references auth.users (id) on delete set null,
    full_name text not null,
    email text not null,
    specialisations text[] not null,
    languages text[] not null,
    bio text not null default '',
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint counsellors_full_name_length
        check (char_length(btrim(full_name)) between 2 and 100),
    constraint counsellors_email_format
        check (email ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$'),
    constraint counsellors_specialisations_allowed
        check (
            cardinality(specialisations) between 1 and 8
            and array_position(specialisations, null) is null
            and specialisations <@ array[
                'Stress', 'Anxiety', 'Academic Pressure', 'Relationships',
                'Sleep', 'Financial', 'Loneliness', 'Other'
            ]::text[]
        ),
    constraint counsellors_languages_valid
        check (
            cardinality(languages) between 1 and 10
            and array_position(languages, null) is null
            and not ('' = any (languages))
        ),
    constraint counsellors_bio_length
        check (char_length(bio) <= 1000)
);

create unique index if not exists counsellors_email_lower_uidx
    on public.counsellors (lower(email));

create index if not exists counsellors_is_active_idx
    on public.counsellors (is_active);

-- A block of time a counsellor is willing to see a student.
-- end_at > start_at is a table check; overlaps are blocked by the GiST
-- exclusion constraint below.
create table if not exists public.availability_slots (
    id uuid primary key default gen_random_uuid(),
    counsellor_id uuid not null references public.counsellors (id) on delete cascade,
    start_at timestamptz not null,
    end_at timestamptz not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint availability_slots_time_order check (end_at > start_at),
    constraint availability_slots_exact_window_key
        unique (counsellor_id, start_at, end_at),
    -- The database itself refuses two overlapping slots for the same
    -- counsellor. The app also checks this to show a friendly message first.
    constraint availability_slots_no_overlap
        exclude using gist (
            counsellor_id with =,
            tstzrange(start_at, end_at, '[)') with &&
        )
);

create index if not exists availability_slots_counsellor_start_idx
    on public.availability_slots (counsellor_id, start_at);

-- One booked counselling session. slot_id points at the chosen free slot.
-- Only pending/confirmed appointments "hold" a slot; see the partial unique
-- index below. Cancelled appointments stay as history but release the slot.
create table if not exists public.appointments (
    id uuid primary key default gen_random_uuid(),
    student_id uuid not null references public.profiles (id) on delete restrict,
    counsellor_id uuid not null references public.counsellors (id) on delete restrict,
    slot_id uuid not null references public.availability_slots (id) on delete restrict,
    mode text not null check (mode in ('in_person', 'online')),
    concern_category text not null
        check (concern_category in (
            'Stress', 'Anxiety', 'Academic Pressure', 'Relationships',
            'Sleep', 'Financial', 'Loneliness', 'Other'
        )),
    note text,
    status text not null default 'pending'
        check (status in ('pending', 'confirmed', 'completed', 'no_show', 'cancelled')),
    follow_up_of uuid references public.appointments (id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint appointments_note_length
        check (note is null or char_length(btrim(note)) <= 1000),
    constraint appointments_follow_up_not_self
        check (follow_up_of is null or follow_up_of <> id)
);

-- A slot can be held by at most one pending/confirmed appointment.
create unique index if not exists appointments_active_slot_uidx
    on public.appointments (slot_id)
    where status in ('pending', 'confirmed');

create index if not exists appointments_student_idx
    on public.appointments (student_id);
create index if not exists appointments_counsellor_idx
    on public.appointments (counsellor_id);
create index if not exists appointments_slot_idx
    on public.appointments (slot_id);
create index if not exists appointments_follow_up_of_idx
    on public.appointments (follow_up_of);

-- A completed session's record. The private notes are only for the counsellor
-- who wrote them. Students read the safe view student_session_summaries.
create table if not exists public.session_records (
    id uuid primary key default gen_random_uuid(),
    appointment_id uuid not null unique
        references public.appointments (id) on delete restrict,
    counsellor_id uuid not null references public.counsellors (id) on delete restrict,
    student_id uuid not null references public.profiles (id) on delete restrict,
    private_notes text not null,
    public_summary text not null,
    risk_level text not null check (risk_level in ('low', 'medium', 'high')),
    follow_up_needed boolean not null default false,
    follow_up_due timestamptz,
    is_archived boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint session_records_private_notes_length
        check (char_length(btrim(private_notes)) between 20 and 5000),
    constraint session_records_public_summary_length
        check (char_length(btrim(public_summary)) between 1 and 2000),
    constraint session_records_follow_up_consistency
        check (
            (follow_up_needed and follow_up_due is not null)
            or (not follow_up_needed and follow_up_due is null)
        )
);

create index if not exists session_records_counsellor_idx
    on public.session_records (counsellor_id);
create index if not exists session_records_student_idx
    on public.session_records (student_id);
create index if not exists session_records_due_idx
    on public.session_records (follow_up_due)
    where follow_up_needed and not is_archived;

