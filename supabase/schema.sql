-- 4. NEW AUTH USER -> PROFILE + ROLE
-- ============================================================================

-- Runs after ANY new auth.users row.
--   * email in admin_whitelist -> admin
--   * email in counsellors    -> counsellor and links counsellors.user_id
--   * everyone else            -> student
-- Any role supplied by the client in metadata is deliberately ignored.
-- Password rules are enforced by Supabase Auth itself (configure the
-- email provider's password policy in the Supabase dashboard).
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $function$
declare
    v_meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
    v_role text := 'student';
    v_counsellor public.counsellors%rowtype;
    v_full_name text;
    v_student_id text;
    v_programme text;
    v_phone text;
    v_preferred_mode text;
    v_email text := lower(btrim(coalesce(new.email, '')));
begin
    if v_email = '' then
        raise exception 'An email address is required for this app.';
    end if;

    if exists (
        select 1
        from public.admin_whitelist aw
        where lower(aw.email) = v_email
    ) then
        v_role := 'admin';
    else
        select *
        into v_counsellor
        from public.counsellors c
        where lower(c.email) = v_email
        limit 1;

        if found then
            v_role := 'counsellor';
        end if;
    end if;

    if v_role = 'student' then
        v_full_name := btrim(coalesce(v_meta ->> 'full_name', ''));
        v_student_id := btrim(coalesce(v_meta ->> 'student_id', ''));
        v_programme := btrim(coalesce(v_meta ->> 'programme', ''));
        v_phone := btrim(coalesce(v_meta ->> 'phone', ''));
        v_preferred_mode := btrim(coalesce(v_meta ->> 'preferred_session_mode', ''));

        if char_length(v_full_name) < 2
           or char_length(v_full_name) > 100
           or char_length(v_student_id) < 3
           or char_length(v_student_id) > 30
           or char_length(v_programme) < 2
           or char_length(v_programme) > 120
           or v_phone = '' then
            raise exception 'Please complete your full name, student ID, programme and phone number.';
        end if;

        if v_phone !~ '^(01[0-9]-[0-9]{7}|\+601[0-9][0-9]{7,8})$' then
            raise exception 'Please enter a valid Malaysian phone number (e.g. 012-3456789 or +60123456789).';
        end if;

        if v_preferred_mode not in ('in_person', 'online') then
            raise exception 'Please choose a preferred session mode.';
        end if;

        if exists (
            select 1
            from public.profiles p
            where p.student_id is not null
              and lower(p.student_id) = lower(v_student_id)
        ) then
            raise exception 'That student ID is already registered.';
        end if;

    elsif v_role = 'counsellor' then
        if v_counsellor.user_id is not null and v_counsellor.user_id <> new.id then
            raise exception 'This counsellor profile is already linked to another account.';
        end if;

        v_full_name := v_counsellor.full_name;
        v_student_id := null;
        v_programme := null;
        v_phone := null;
        v_preferred_mode := null;

    else
        v_full_name := left(
            coalesce(nullif(btrim(coalesce(v_meta ->> 'full_name', '')), ''), 'System Administrator'),
            100
        );
        v_student_id := null;
        v_programme := null;
        v_phone := null;
        v_preferred_mode := null;
    end if;

    insert into public.profiles (
        id, email, role, full_name, student_id, programme, phone,
        preferred_session_mode, is_active
    )
    values (
        new.id, v_email, v_role, v_full_name, v_student_id, v_programme, v_phone,
        v_preferred_mode, true
    );

    if v_role = 'counsellor' then
        update public.counsellors
        set user_id = new.id,
            updated_at = now()
        where id = v_counsellor.id;
    end if;

    return new;
end;
$function$;

