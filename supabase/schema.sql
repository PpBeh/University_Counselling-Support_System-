-- Module 3 delete: admin removes a counsellor. The rules are:
--   * block while any upcoming pending/confirmed appointment exists
--   * if the counsellor has any appointment history, only deactivate
--   * otherwise hard delete the directory entry (and cascade its free slots);
--     if an Auth account was linked, deactivate that login too
-- Returns 'deleted' or 'deactivated' so the app can show the correct Snackbar.
create or replace function public.delete_counsellor(
    p_counsellor_id uuid
)
returns text
language plpgsql
security definer
set search_path = public, auth
as $function$
declare
    v_counsellor record;
    v_upcoming_count integer;
    v_has_history boolean;
begin
    if public.app_role() <> 'admin' then
        raise exception 'Only administrators can remove counsellors.';
    end if;

    select c.id, c.full_name, c.user_id
    into v_counsellor
    from public.counsellors c
    where c.id = p_counsellor_id
    for update;

    if not found then
        raise exception 'That counsellor could not be found.';
    end if;

    select count(*)
    into v_upcoming_count
    from public.appointments a
    join public.availability_slots s on s.id = a.slot_id
    where a.counsellor_id = p_counsellor_id
      and a.status in ('pending', 'confirmed')
      and s.start_at > now();

    if v_upcoming_count > 0 then
        raise exception 'This counsellor has upcoming appointments. Resolve them before removing the counsellor.';
    end if;

    select exists (
        select 1 from public.appointments a where a.counsellor_id = p_counsellor_id
    )
    into v_has_history;

    if v_has_history then
        update public.counsellors
        set is_active = false
        where id = p_counsellor_id;
        return 'deactivated';
    end if;

    -- A counsellor with no session history can be hard-deleted from the
    -- directory. If an Auth account is linked, disable that login too, so the
    -- account cannot keep a counsellor role with no counsellor record.
    if v_counsellor.user_id is not null then
        update public.profiles
        set is_active = false
        where id = v_counsellor.user_id;
    end if;

    delete from public.counsellors where id = p_counsellor_id;
    return 'deleted';
end;
$function$;

-- Module 6 create: submit an enquiry as the signed-in student and return the
-- generated reference code. This is a function (not a direct insert) so the
-- app can receive the code even for anonymous rows, which have no SELECT
-- policy at all. Anonymous rows store no student id.
create or replace function public.submit_enquiry(
    p_category text,
    p_message text,
    p_is_anonymous boolean default false
)
returns text
language plpgsql
security definer
set search_path = public, auth
as $function$
declare
    v_student_id uuid := auth.uid();
    v_profile record;
    v_category text := btrim(coalesce(p_category, ''));
    v_message text := btrim(coalesce(p_message, ''));
    v_is_anonymous boolean := coalesce(p_is_anonymous, false);
    v_reference_code text;
    v_stored_student_id uuid;
begin
    if v_student_id is null then
        raise exception 'Please sign in again.';
    end if;

    select p.role, p.is_active
    into v_profile
    from public.profiles p
    where p.id = v_student_id;

    if not found then
        raise exception 'Only active students can submit enquiries.';
    end if;

    if v_profile.role <> 'student' or not v_profile.is_active then
        raise exception 'Only active students can submit enquiries.';
    end if;

    if v_category = '' or v_category not in (
        'Stress', 'Anxiety', 'Academic Pressure', 'Relationships',
        'Sleep', 'Financial', 'Loneliness', 'Other'
    ) then
        raise exception 'Please choose a concern category.';
    end if;

    if char_length(v_message) < 10 or char_length(v_message) > 1000 then
        raise exception 'Your message must be between 10 and 1,000 characters.';
    end if;

    v_stored_student_id := case when v_is_anonymous then null else v_student_id end;

    loop
        v_reference_code := 'ENQ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));
        exit when not exists (
            select 1 from public.enquiries e where e.reference_code = v_reference_code
        );
    end loop;

    insert into public.enquiries (
        reference_code, student_id, is_anonymous, category, message, status
    )
    values (
        v_reference_code, v_stored_student_id, v_is_anonymous, v_category,
        v_message, 'open'
    );

    return v_reference_code;
end;
$function$;

-- Anonymous-safe lookup: returns no student identity and no private notes,
-- only the enquiry text, reply and attached published resource.
create or replace function public.get_enquiry_by_code(
    p_code text
)
returns table (
    reference_code text,
    category text,
    message text,
    reply text,
    status text,
    recommended_resource_id uuid,
    recommended_resource_title text,
    created_at timestamptz,
    replied_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, auth
as $function$
declare
    v_code text := upper(btrim(coalesce(p_code, '')));
begin
    if public.app_role() is null then
        raise exception 'Your account is not active. Please sign in again.';
    end if;

    if v_code !~ '^ENQ-[A-Z0-9]{6}$' then
        raise exception 'Please enter a valid reference code (for example ENQ-7K3P9Q).';
    end if;

    return query
    select e.reference_code,
           e.category,
           e.message,
           e.reply,
           e.status,
           e.recommended_resource_id,
           r.title,
           e.created_at,
           e.replied_at
    from public.enquiries e
    left join public.resources r
      on r.id = e.recommended_resource_id
     and r.is_published = true
    where e.reference_code = v_code;
end;
$function$;

-- Anonymous-safe withdrawal: anyone holding the code can delete an OPEN
-- enquiry. Answered/closed enquiries are read-only.
create or replace function public.withdraw_enquiry_by_code(
    p_code text
)
returns void
language plpgsql
security definer
set search_path = public, auth
as $function$
declare
    v_code text := upper(btrim(coalesce(p_code, '')));
    v_deleted integer;
begin
    if public.app_role() is null then
        raise exception 'Your account is not active. Please sign in again.';
    end if;

    if v_code !~ '^ENQ-[A-Z0-9]{6}$' then
        raise exception 'Please enter a valid reference code (for example ENQ-7K3P9Q).';
    end if;

    delete from public.enquiries
    where reference_code = v_code
      and status = 'open';

    get diagnostics v_deleted = row_count;

    if v_deleted = 0 then
        raise exception 'No open enquiry was found for that reference code.';
    end if;
end;
$function$;

-- Admin-only aggregate dashboard. It returns counts and an average rating,
-- never private notes or individual session content.
create or replace function public.admin_dashboard_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $function$
begin
    if public.app_role() <> 'admin' then
        raise exception 'Only administrators can view dashboard statistics.';
    end if;

    return jsonb_build_object(
        'total_students', (
            select count(*) from public.profiles where role = 'student'
        ),
        'active_students', (
            select count(*) from public.profiles where role = 'student' and is_active
        ),
        'total_counsellors', (
            select count(*) from public.counsellors
        ),
        'active_counsellors', (
            select count(*) from public.counsellors where is_active
        ),
        'total_appointments', (
            select count(*) from public.appointments
        ),
        'upcoming_appointments', (
            select count(*)
            from public.appointments a
            join public.availability_slots s on s.id = a.slot_id
            where a.status in ('pending', 'confirmed')
              and s.start_at > now()
        ),
        'completed_appointments', (
            select count(*) from public.appointments where status = 'completed'
        ),
        'session_records', (
            select count(*) from public.session_records where not is_archived
        ),
        'total_resources', (
            select count(*) from public.resources
        ),
        'published_resources', (
            select count(*) from public.resources where is_published
        ),
        'feedback_count', (
            select count(*) from public.feedback
        ),
        'average_rating', (
            select coalesce(round(avg(f.rating)::numeric, 2), 0)
            from public.feedback f
        )
    );
end;
$function$;

