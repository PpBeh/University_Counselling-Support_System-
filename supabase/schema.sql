-- One row for every Supabase Auth user. The auth.users trigger fills this in.
create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    email text not null,
    role text not null default 'student'
        check (role in ('student', 'counsellor', 'admin')),
    full_name text not null,
    student_id text,
    programme text,
    phone text,
    preferred_session_mode text
        check (preferred_session_mode is null or preferred_session_mode in ('in_person', 'online')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint profiles_full_name_length
        check (char_length(btrim(full_name)) between 2 and 100),
    constraint profiles_student_id_length
        check (student_id is null or char_length(btrim(student_id)) between 3 and 30),
    constraint profiles_programme_length
        check (programme is null or char_length(btrim(programme)) between 2 and 120),
    constraint profiles_phone_format
        check (
            phone is null
            or phone ~ '^(01[0-9]-[0-9]{7}|\+601[0-9][0-9]{7,8})$'
        ),
    -- Students must always have the four fields collected during registration.
    constraint profiles_student_fields_required
        check (
            role <> 'student'
            or (
                student_id is not null
                and programme is not null
                and phone is not null
                and preferred_session_mode is not null
            )
        )
);

-- Emails are unique without caring about case.
create unique index if not exists profiles_email_lower_uidx
    on public.profiles (lower(email));

-- Student IDs are unique without caring about case, but admins/counsellors
-- may legitimately have a null student ID, so this is a partial index.
create unique index if not exists profiles_student_id_lower_uidx
    on public.profiles (lower(student_id))
    where student_id is not null;

create index if not exists profiles_role_idx on public.profiles (role);

